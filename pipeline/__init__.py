"""clip-pipeline — конвейер нарезки длинных видео в вертикальные клипы для CPM-кампаний.

Модули:
    config      — настройки, пути, шрифты, выбор бэкенда распознавания
    campaign    — чтение и проверка спецификации кампании (campaigns/*.json)
    download    — получение исходника (локальный файл или ссылка через yt-dlp)
    transcribe  — извлечение звука и расшифровка (faster-whisper или sherpa-onnx)
    audio_features — энергия звука по окнам для оценки фрагментов
    segment     — разбиение расшифровки на предложения и подбор кандидатов
    score_llm   — необязательная оценка кандидатов языковой моделью
    subtitles   — сборка ASS-субтитров из слов
    render      — ffmpeg: кадрирование 9:16, субтитры, хук, баннер, финальная плашка
    captions    — подписи, хештеги и чек-лист правил под каждую площадку
    tracker     — учёт исходников, клипов, публикаций и просмотров (SQLite)
    report      — недельный отчёт по ключевым цифрам
    cli         — командная строка: python -m pipeline <команда>
"""

